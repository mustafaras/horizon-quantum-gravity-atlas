import { test, expect } from 'playwright/test';
test.skip(process.env.QGA_WEBGPU_HEADED !== '1', 'Requires an explicitly enabled headed browser with a WebGPU adapter.');
test.use({ headless: false, launchOptions: { args: ['--enable-unsafe-webgpu'] } });
test.setTimeout(180000);
test('native WebGPU renders the S20 scenes when an adapter is available', async ({ page, context }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.addInitScript(() => { window.QGA_RENDER_OPTIONS = { forceBackend: 'webgpu' }; sessionStorage.setItem('horizon-intro', '1'); });
  await page.goto('/?view=gr&seed=42', { waitUntil: 'domcontentloaded' });
  const available = await page.evaluate(async () => !!(navigator.gpu && await navigator.gpu.requestAdapter().catch(() => null)));
  test.skip(!available, 'No WebGPU adapter is available on this browser.');
  await page.locator('.tidal-scene-shell').scrollIntoViewIfNeeded({ timeout: 90000 });
  await expect.poll(async () => page.evaluate(() => { const e = window.QGA_RENDER?.renderDiagnostics.snapshot().find(x => /ring of test particles/i.test(x.label)); return e && { backend: e.backend, phase: e.phase }; }), { timeout: 90000 }).toEqual({ backend: 'webgpu', phase: 'ready' });
  const canvas = page.locator('.tidal-lab .s3d-canvas');
  await expect(canvas).toBeVisible();
  await expect.poll(async () => page.evaluate(() => { const stage=QGA_RENDER.stageDiagnostics.snapshot().find(s=>s.kind==='webgpu'); return stage?.views.find(v=>/ring of test particles/i.test(v.label))?.frames || 0; }), { timeout: 90000 }).toBeGreaterThan(0);
  const before = await canvas.screenshot();
  await page.getByLabel('Fall progress').fill('760');
  await canvas.evaluate(el => el.scrollIntoView({ block: 'center' }));
  await expect.poll(async () => page.evaluate(() => QGA_RENDER.stageDiagnostics.snapshot().some(s => s.views.some(v => /ring of test particles/i.test(v.label) && v.visible))), { timeout: 30000 }).toBe(true);
  await expect.poll(async () => page.evaluate(() => { const s = [...window.__qgaActiveScenes].find(scene => scene.element.closest('.tidal-lab'))?.state(); return !!s && s.transverse < 0.1 && s.settleFrames === 0; }), { timeout: 30000 }).toBe(true);
  await expect.poll(async () => !(await canvas.screenshot()).equals(before), { timeout: 30000 }).toBe(true);
  await page.locator('.gr-well-stage').scrollIntoViewIfNeeded();
  await expect.poll(async () => page.evaluate(() => { const e = window.QGA_RENDER?.renderDiagnostics.snapshot().find(x => /gravity well/i.test(x.label)); return e && { backend: e.backend, phase: e.phase }; }), { timeout: 90000 }).toEqual({ backend: 'webgpu', phase: 'ready' });
  await expect(page.locator('.gr-geometry-label')).toContainText('EXACT');
  await expect.poll(async () => page.evaluate(() => QGA_RENDER.stageDiagnostics.snapshot().find(s => s.kind === 'webgpu')?.views.find(v => /gravity well/i.test(v.label))?.frames || 0), { timeout: 90000 }).toBeGreaterThan(0);
  const flammCanvas = page.locator('.gr-well-stage .s3d-canvas');
  await expect(flammCanvas).toBeVisible();
  expect((await flammCanvas.screenshot()).length).toBeGreaterThan(8000);
  expect(errors).toEqual([]);
});
