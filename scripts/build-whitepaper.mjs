// Whitepaper v2 generator (S35). One source, two outputs:
//   js/whitepaper/whitepaper-v2-data.mjs   the frozen data the in-app paper view renders (through js/bootstrap.mjs)
//   docs/whitepaper.md                     the block between the whitepaper-v2 markers
// Inputs: the ledger (verification record), the provenance registry (coverage counts) and the Formula Core library
// (definition count), so no number in the section is typed by hand.
//
//   node scripts/build-whitepaper.mjs           write both outputs
//   node scripts/build-whitepaper.mjs --check   exit 1 if a committed output is stale (run by `npm run validate`)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildWhitepaperV2, renderWhitepaperMarkdown, BLOCK_BEGIN, BLOCK_END } from "../js/whitepaper/whitepaper-v2.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA_MODULE = "js/whitepaper/whitepaper-v2-data.mjs";
const MARKDOWN = "docs/whitepaper.md";
// A first run inserts the block before the references.
const INSERT_BEFORE = "\n## References";

export async function collectWhitepaperInputs(root = ROOT) {
  const ledger = JSON.parse(fs.readFileSync(path.join(root, "docs/superpowers/ledger/ledger.json"), "utf8"));
  const { registerAllProvenance } = await import("../js/provenance-index.mjs");
  const { listVisualizationProvenance } = await import("../js/science/provenance.mjs");
  const { library } = await import("../js/formula/library/index.mjs");
  registerAllProvenance();
  const provenanceStatuses = {};
  for (const { provenance } of listVisualizationProvenance()) {
    provenanceStatuses[provenance.status] = (provenanceStatuses[provenance.status] ?? 0) + 1;
  }
  return { ledger, provenanceStatuses, formulaDefinitions: Object.keys(library).length };
}

function dataModuleSource(data) {
  return [
    "// Generated by scripts/build-whitepaper.mjs from js/whitepaper/whitepaper-v2.mjs, the ledger, the provenance",
    "// registry and the Formula Core library. Do not edit: run `npm run build:whitepaper`.",
    "",
    "const deepFreeze = (value) => {",
    "  if (value && typeof value === \"object\") Object.values(value).forEach(deepFreeze);",
    "  return Object.freeze(value);",
    "};",
    "",
    `export const WHITEPAPER_V2 = deepFreeze(${JSON.stringify(data, null, 2)});`,
    "",
  ].join("\n");
}

function spliceBlock(markdown, block) {
  const begin = markdown.indexOf(BLOCK_BEGIN);
  if (begin !== -1) {
    const end = markdown.indexOf(BLOCK_END, begin);
    if (end === -1) throw new Error(`${MARKDOWN}: ${BLOCK_BEGIN} has no matching end marker`);
    return markdown.slice(0, begin) + block + markdown.slice(end + BLOCK_END.length);
  }
  const at = markdown.indexOf(INSERT_BEFORE);
  if (at === -1) throw new Error(`${MARKDOWN}: no generated block and no "## References" heading to insert before`);
  return `${markdown.slice(0, at)}\n${block}\n\n---\n${markdown.slice(at)}`;
}

/** Both outputs as strings, from the inputs and the current docs/whitepaper.md. */
export function generateWhitepaperOutputs(inputs, currentMarkdown) {
  const data = buildWhitepaperV2(inputs);
  return { data, dataModule: dataModuleSource(data), markdown: spliceBlock(currentMarkdown, renderWhitepaperMarkdown(data)) };
}

async function main(argv) {
  const check = argv.includes("--check");
  const mdPath = path.join(ROOT, MARKDOWN);
  const dataPath = path.join(ROOT, DATA_MODULE);
  const outputs = generateWhitepaperOutputs(await collectWhitepaperInputs(), fs.readFileSync(mdPath, "utf8"));
  const summary = `${outputs.data.record.total} measurements from ${outputs.data.record.prompts.length} prompts`;
  if (check) {
    const stale = [[dataPath, DATA_MODULE, outputs.dataModule], [mdPath, MARKDOWN, outputs.markdown]]
      .filter(([file, , expected]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected)
      .map(([, name]) => name);
    for (const name of stale) console.error(`${name} is stale: run npm run build:whitepaper`);
    if (stale.length) process.exit(1);
    console.log(`✓ whitepaper v2 is current (${summary})`);
    return;
  }
  fs.mkdirSync(path.dirname(dataPath), { recursive: true });
  fs.writeFileSync(dataPath, outputs.dataModule);
  fs.writeFileSync(mdPath, outputs.markdown);
  console.log(`wrote ${DATA_MODULE} and the v2 block of ${MARKDOWN}: ${summary}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main(process.argv.slice(2));
