#!/usr/bin/env node
/**
 * Collect the cover sidecars into one module the header can read (S29).
 *
 *   node scripts/build-cover-index.mjs           write js/science/data/cover-index.mjs
 *   node scripts/build-cover-index.mjs --check    fail if the committed file is stale
 *
 * `js/core.jsx` is a classic script, so it cannot read JSON at runtime. Without the measured widths it had to guess,
 * and it guessed 1200w/2400w for files that are 794 and 950 px wide. This module carries the truth instead.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const coversDir = path.join(root, "docs/covers");
const target = path.join(root, "js/science/data/cover-index.mjs");
const check = process.argv.includes("--check");

const slugs = ["standard-model", "qft", "rg", "gr", "planck", "approaches", "blackholes", "experiments"];
const index = {};

for (const slug of slugs) {
  const sidecar = JSON.parse(await readFile(path.join(coversDir, `${slug}.json`), "utf8"));
  if (!Array.isArray(sidecar.sizes) || sidecar.sizes.length !== 2) {
    throw new Error(`${slug}: sidecar must record both rendered sizes`);
  }
  index[slug] = {
    sizes: sidecar.sizes.map((s) => ({ file: s.file, width: s.width, height: s.height })),
    aspect: sidecar.aspect,
    target: sidecar.target,
    commit: sidecar.commit,
  };
}

const body = `// Generated by scripts/build-cover-index.mjs — do not edit by hand.
// The measured pixel size of each chapter cover, so the header describes the files it actually has.
export const COVER_INDEX = Object.freeze(${JSON.stringify(index, null, 2)});
`;

if (check) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== body) {
    console.error("cover-index.mjs is stale: run node scripts/build-cover-index.mjs");
    process.exit(1);
  }
  console.log(`✓ cover index matches ${slugs.length} sidecars`);
} else {
  await writeFile(target, body);
  console.log(`✓ wrote ${path.relative(root, target)} for ${slugs.length} covers`);
}
