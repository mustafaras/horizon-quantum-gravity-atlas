// Writes the generated block of docs/release-verification.md (S36): the S03-S28 ledger measurements re-measured
// today, and how every one of the 155 is re-measured. The rest of the document is written by hand.
//
//   node scripts/build-release-verification.mjs           write the block
//   node scripts/build-release-verification.mjs --check   exit 1 if the committed block is stale or a re-measurement
//                                                         left the ledger's precision (run by `npm run validate`)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MEASUREMENT_CLASSES, RERUN_BY, runRemeasurements } from "./release/remeasure.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOC = "docs/release-verification.md";
export const BEGIN = "<!-- release-verification:begin (generated by scripts/build-release-verification.mjs; do not edit) -->";
export const END = "<!-- release-verification:end -->";

const CLASS_NAMES = Object.freeze({
  N: "recomputed here", T: "node:test", B: "browser/GPU spec", P: "timing (perf:collect)", A: "static count (perf:audit)", S: "primary-source reading",
});

const fmt = (x) => (Number.isInteger(x) ? String(x) : Math.abs(x) >= 1e4 || (Math.abs(x) < 1e-3 && x !== 0) ? x.toExponential(6) : String(Number(x.toPrecision(10))));

export function classTally(classes = MEASUREMENT_CLASSES) {
  const tally = Object.fromEntries(Object.keys(CLASS_NAMES).map((k) => [k, 0]));
  for (const codes of Object.values(classes)) for (const c of codes) tally[c] += 1;
  return tally;
}

export function renderBlock(rows) {
  const tally = classTally();
  const total = Object.values(tally).reduce((a, b) => a + b, 0);
  const passed = rows.filter((r) => r.pass).length;
  const lines = [BEGIN, "", "### Re-measured from the science modules", "",
    `${passed} of ${rows.length} values recomputed today agree with the ledger within the precision the ledger quotes.`, "",
    "| Ledger entry | Quantity | Ledger | Today | Difference | Tolerance | |", "|---|---|---|---|---|---|---|"];
  for (const r of rows) {
    lines.push(`| ${r.ref} | ${r.label} | ${fmt(r.ledger)} | ${fmt(r.value)} | ${fmt(r.difference)} | ${fmt(r.tol)} | ${r.pass ? "ok" : "**differs**"} |`);
  }
  lines.push("", "### How each of the ledger's measurements is re-measured", "",
    `${total} measurements in S03–S28: ${Object.entries(tally).map(([k, n]) => `${n} ${CLASS_NAMES[k]} (${k})`).join(", ")}.`, "",
    "| Prompt | Entries in ledger order | Re-run by |", "|---|---|---|");
  for (const [prompt, codes] of Object.entries(MEASUREMENT_CLASSES)) lines.push(`| ${prompt} | \`${codes}\` | ${RERUN_BY[prompt]} |`);
  lines.push("", END);
  return lines.join("\n");
}

export function splice(markdown, block) {
  const begin = markdown.indexOf(BEGIN), end = markdown.indexOf(END);
  if (begin === -1 || end === -1 || end < begin) throw new Error(`${DOC}: the generated-block markers are missing`);
  return markdown.slice(0, begin) + block + markdown.slice(end + END.length);
}

function main(argv) {
  const rows = runRemeasurements();
  const file = path.join(ROOT, DOC);
  const current = fs.readFileSync(file, "utf8");
  const next = splice(current, renderBlock(rows));
  const differs = rows.filter((r) => !r.pass);
  if (argv.includes("--check")) {
    for (const r of differs) console.error(`${r.ref} ${r.label}: ledger ${r.ledger}, today ${r.value}`);
    if (next !== current) console.error(`${DOC} is stale: run node scripts/build-release-verification.mjs`);
    if (differs.length || next !== current) process.exit(1);
    console.log(`✓ release verification is current (${rows.length} re-measurements within the ledger's precision)`);
    return;
  }
  fs.writeFileSync(file, next);
  console.log(`wrote the generated block of ${DOC}: ${rows.length - differs.length}/${rows.length} within precision`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
