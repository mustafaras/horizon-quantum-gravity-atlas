// GitHub renders $…$ as mathematics and * or _ as emphasis; a ledger string is literal text.
const escapeMarkdown = (text) => text.replace(/([\\`*_$<>[\]|])/g, "\\$1");

/** The generated Markdown block, markers included. */
export function renderWhitepaperMarkdown(data) {
  const lines = [BLOCK_BEGIN, "", `## ${data.index}. ${data.title}`, "", data.intro, ""];
  for (const section of data.sections) {
    lines.push(`### ${section.index} ${section.title}`, "");
    for (const paragraph of section.paragraphs) lines.push(paragraph, "");
  }
  for (const prompt of data.record.prompts) {
    lines.push(`#### ${prompt.id} — ${prompt.title}`, "");
    if (prompt.measurements.length === 0) lines.push("- no measurement recorded");
    for (const m of prompt.measurements) lines.push(`- ${escapeMarkdown(m)}`);
    lines.push("");
  }
  lines.push(BLOCK_END);
  return lines.join("\n");
}
