// Whitepaper v2 (S35): the single source of the paper's version-2 section. Both outputs come from here:
// scripts/build-whitepaper.mjs writes js/whitepaper/whitepaper-v2-data.mjs (read by the in-app paper view through
// js/bootstrap.mjs) and the generated block of docs/whitepaper.md. The verification record is copied verbatim from the
// ledger, never retyped, and the provenance and Formula Core counts are computed by the generator. Pure and DOM-free.

export const BLOCK_BEGIN = "<!-- whitepaper-v2:begin (generated by scripts/build-whitepaper.mjs; do not edit) -->";
export const BLOCK_END = "<!-- whitepaper-v2:end -->";

const STATUS_ORDER = Object.freeze(["established", "effective", "schematic", "conjectural", "open", "heuristic"]);

const promptNumber = (id) => Number(String(id).slice(1));

/** The ledger's evidence.measurements for prompts `from`..`to`, in ledger order, as written. */
export function verificationRecord(ledger, { from, to }) {
  const lo = promptNumber(from), hi = promptNumber(to);
  const prompts = ledger.prompts
    .filter((p) => promptNumber(p.id) >= lo && promptNumber(p.id) <= hi)
    .map((p) => ({ id: p.id, title: p.title, measurements: [...(p.evidence?.measurements ?? [])] }));
  return { from, to, total: prompts.reduce((n, p) => n + p.measurements.length, 0), prompts };
}

function provenanceSentence(statuses) {
  const total = Object.values(statuses).reduce((a, b) => a + b, 0);
  const known = STATUS_ORDER.filter((s) => statuses[s]).map((s) => `${statuses[s]} ${s}`);
  const other = Object.keys(statuses).filter((s) => !STATUS_ORDER.includes(s)).map((s) => `${statuses[s]} ${s}`);
  return { total, breakdown: [...known, ...other].join(", ") };
}

