/* ---------- Prompt 08: collider event display (shared by standard model + experiments) ---------- */
function ColliderLabSection({ compact = false, fallback = null } = {}) {
  const [state, setState] = useQGAState();
  const [sel, setSel] = useState(null);
  const selRef = useRef(sel); selRef.current = sel;
  const channel = state.colliderChannel;
  const seed = state.seed;
  const lab = window.QGA_LABS && window.QGA_LABS.eventSummary
    ? window.QGA_LABS.eventSummary(window.QGA_LABS.syntheticEvent({ channel, seed, sqrtSGev: 13600 })) : null;
  const channelLabels = {
    h2gg: "H → γγ", z2mm: "Z → μμ", z2ee: "Z → ee", ttbar: "t t̄", qcd: "QCD jets",
  };

  const build = async (ctx) => {
    const LABS = window.QGA_LABS;
    if (!LABS) throw new Error("Compute-lab module unavailable");
    const { createColliderDisplayRuntime } = await LABS.loadColliderDisplay();
    ctx.scene.fog = new ctx.THREE.FogExp2(QGA_TOKENS.hex("pigment-grey-11-c02-h261"), 0.014);
    const runtime = createColliderDisplayRuntime({ channel, seed, sqrtSGev: 13600, camera: ctx.camera, engraved: ctx.engraved });
    ctx.scene.add(runtime.mesh);
    ctx.label("SYNTHETIC FIXTURE · seeded kinematics — not a CERN observation",
      () => ({ x: -4.6, y: 3.6, z: -3.4 }), "s3d-strong");
    ctx.label("tracker · ECAL · HCAL · muon system — click a track to identify it",
      () => ({ x: -4.6, y: -3.4, z: 3.4 }), "s3d-quiet");
    return {
      pickables: runtime.pickables,
      onPick: (o) => {
        if (o && o.userData && o.userData.info) setSel(o.userData);
      },
      update: (t) => {
        runtime.sync({ time: t, motion: ctx.motion() === 0 ? 0 : 1 });
        window.__qgaColliderLab = { kind: runtime.kind, ...runtime.stats() };
      },
      dispose: () => {
        runtime.dispose();
        delete window.__qgaColliderLab;
      },
      recoverable: () => false,
    };
  };

  return (
    <div className="viz-frame">
      <div className="viz-toolbar lab-toolbar">
        <div className="kerr-control-group" aria-label="Collider channel">
          <span className="kerr-control-label">Channel</span>
          {Object.entries(channelLabels).map(([key, label]) => (
            <button key={key} className={"kerr-chip" + (channel === key ? " on" : "")}
              aria-pressed={channel === key} onClick={() => setState({ colliderChannel: key })}>{label}</button>
          ))}
        </div>
        <button className="kerr-chip" onClick={() => setState({ seed: seed + 1 })}>New collision</button>
        {sel !== null ? <button className="kerr-chip" onClick={() => setSel(null)}>Clear selection</button> : null}
        <div className="kerr-state-line lab-readout">
          {lab ? <>{lab.nParticles} particles · {lab.nJets} jets ·
            {lab.masses.mGammaGamma != null ? <> m<sub>γγ</sub> = {lab.masses.mGammaGamma.toFixed(1)} GeV ·</> : null}
            {lab.masses.mMuMu != null ? <> m<sub>μμ</sub> = {lab.masses.mMuMu.toFixed(1)} GeV ·</> : null}
            {lab.masses.mTopHad != null ? <> m<sub>t</sub> = {lab.masses.mTopHad.toFixed(0)} GeV ·</> : null}
            E<sub>T</sub><sup>miss</sup> = {lab.metEt.toFixed(0)} GeV</> : "—"}
        </div>
      </div>
      <Scene3D animated="motion" height={compact ? 400 : 460}
        aria="Three-dimensional collider event display: two beams collide at the vertex, charged tracks curve in the tracker, calorimeter towers rise with transverse energy, jet cones mark hadronic clusters, and a dashed arrow shows missing transverse energy"
        initial={{ radius: 13, theta: 0.95, phi: 1.15, minR: 5, maxR: 34, bloom: { strength: 0.7, radius: 0.5, threshold: 0.18 } }}
        build={build} deps={[channel, seed]}
        fallback={fallback || <div className="lab-fallback">The 3-D event display needs WebGL; the kinematics above are computed without it.</div>}></Scene3D>
      {sel ? (
        <div className="s3d-detail" aria-live="polite">
          <span className="badge badge-schematic">{sel.kind || "deposit"}</span>
          <span className="small" style={{ flex: 1 }}>{sel.info}</span>
        </div>
      ) : null}
      <VizCaption status="schematic">
        Every particle here is generated by <code>js/science/collider-kinematics.mjs</code> from the shared seed:
        two-body decays with exact four-momentum conservation, on-shell masses, and a seeded jet clusterer
        (anti-k<sub>T</sub>-style greedy merging, disclosed as a teaching approximation). Tracks curve by charge
        over p<sub>T</sub>, calorimeter towers bin real (η, φ) coordinates, and the dashed arrow is the vector sum
        that balances transverse momentum — the classic neutrino signature. This is a <strong>schematic
        synthetic fixture</strong> for learning detector logic; it is not a CERN observation and carries no
        experimental claim.
      </VizCaption>
    </div>);
}