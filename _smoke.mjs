import { chromium } from "playwright";
const qs = process.argv[2] || "view=bh&bhm=1&bhs=0.9&seed=42";
const out = process.argv[3] || "/tmp/kerr-smoke.png";
const browser = await chromium.launch({ args: ["--ignore-gpu-blocklist"] });
const context = await browser.newContext({ viewport: { width: 1400, height: 1000 }, reducedMotion: process.env.RM ? "reduce" : "no-preference" });
await context.addInitScript(() => { window.QGA_RENDER_OPTIONS = { forceBackend: "webgl2", softwareClamp: false }; sessionStorage.setItem("horizon-intro", "1"); });
const page = await context.newPage();
const logs = [];
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) logs.push(m.type() + ": " + m.text().slice(0, 400)); });
page.on("pageerror", (e) => logs.push("pageerror: " + (e.stack || e.message).slice(0, 600)));
await page.goto("http://127.0.0.1:8790/?" + qs, { waitUntil: "domcontentloaded" });
await page.waitForSelector(".s3d-canvas", { timeout: 90000 }).catch((e) => logs.push("no canvas: " + e.message.slice(0,100)));
await page.waitForTimeout(Number(process.env.WAIT || 6000));
const info = await page.evaluate(() => ({ rt: window.__qgaKerrRuntime && { backend: window.__qgaKerrRuntime.backend, frames: window.__qgaKerrRuntime.frames, resets: window.__qgaKerrRuntime.resets, res: window.__qgaKerrRuntime.resolution }, diag: window.QGA_RENDER?.renderDiagnostics.snapshot().map((d) => ({ phase: d.phase, backend: d.backend, label: d.label, msgs: (d.messages||[]).slice(-3) })) }));
console.log(JSON.stringify(info, null, 1));
const stage = page.locator(".s3d-stage").first();
await stage.scrollIntoViewIfNeeded();
await stage.screenshot({ path: out });
console.log(logs.join("\n") || "no console errors");
await browser.close();
